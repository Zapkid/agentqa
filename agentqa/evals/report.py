README = REPO_ROOT / "README.md"
BEGIN, END = (
    "<!-- results:begin (generated by agentqa eval; do not edit) -->",
    "<!-- results:end -->",
)
LABELS = {
    "S0": "S0 strong model for everything",
    "S1": "S1 cheap model for everything",
    "S2": "S2 static role routing",
    "S3": "**S3 smart dispatcher**",
}


def latest_results() -> tuple[Path | None, Path | None]:
    """Newest functional and perf result files. Names start with the date, so sort by name (a
    fresh checkout gives every file the same modification time)."""
    files = sorted(RESULTS.glob("*.json"), key=lambda p: p.name)
    func = next((p for p in reversed(files) if "perf" not in p.name), None)
    perf = next((p for p in reversed(files) if "perf" in p.name), None)
    return func, perf


def _range_pct(v: dict[str, float]) -> str:
    mean, lo, hi = v["mean"] * 100, v["min"] * 100, v["max"] * 100
    return f"{mean:.0f}%" if round(lo) == round(hi) else f"{mean:.0f}% ({lo:.0f}–{hi:.0f}%)"


def _n(count: int, noun: str) -> str:
    return f"{count} {noun}" + ("" if count == 1 else "s")


def _k(tokens: float) -> str:
    return f"{tokens / 1000:.1f}k" if tokens < 10_000 else f"{tokens / 1000:.0f}k"


def readme_results(func: dict[str, Any] | None, perf: dict[str, Any] | None) -> str:
    """The README's Results section body, computed from the result files only."""
    out: list[str] = []
    if func and "strategies" in func:
        st = func["strategies"]
        sim = "simulated" in json.dumps(func.get("profiles", ["simulated"]))
        n = st["S3"]["aggregate"]["n"]
        if sim:
            out += [
                "All numbers below come from **simulated models** (declared error rates, ADR 0003).",
                "",
            ]
        out += [
            f"**Cost vs quality: four strategies, {n} cold runs each "
            "(mean, with min–max where it varied)**",
            "",
            "| strategy | bug recall | triage accuracy | hallucination (pre-repair) "
            "| list-equivalent $ / run | $ per bug found |",
            "|---|---|---|---|---|---|",
        ]
        for name, label in LABELS.items():
            a = st[name]["aggregate"]
            cells = [
                _range_pct(a["recall"]),
                f"{a['triage_accuracy']['mean']:.2f}",
                f"{a['hallucination_rate']['mean'] * 100:.0f}%",
                f"{a['cost_usd_list_equivalent']['mean']:.3f}",
                f"{a['cost_per_bug_list_equivalent']['mean']:.4f}",
            ]
            if name == "S3":
                cells = [f"**{c}**" if i != 2 else c for i, c in enumerate(cells)]
            out.append(f"| {label} | " + " | ".join(cells) + " |")
        s0, s3 = st["S0"]["aggregate"], st["S3"]["aggregate"]
        d_recall = (s3["recall"]["mean"] - s0["recall"]["mean"]) * 100
        ratio = s3["cost_usd_list_equivalent"]["mean"] / max(
            1e-9, s0["cost_usd_list_equivalent"]["mean"]
        )
        ablations = {k[6:]: v["aggregate"] for k, v in st.items() if k.startswith("S3-no-")}
        worst = min(ablations, key=lambda k: ablations[k]["recall"]["mean"]) if ablations else None
        out += [
            "",
            f"Hypothesis targets: S3 within 5 points of S0's recall → **{d_recall:+.1f} points "
            f"({'met' if d_recall >= -5 else 'missed'})**; S3 at most half of S0's cost → "
            f"**{ratio:.0%} ({'met' if ratio <= 0.5 else 'missed'})**. S3 used "
            f"{_k(s3['tokens_total']['mean'])} tokens per run against S0's "
            f"{_k(s0['tokens_total']['mean'])}, so the saving comes from tiering (cheap models "
            "do most of the work, gated by verification and escalation), not from fewer tokens.",
        ]
        if worst:
            w = ablations[worst]
            out += [
                "",
                f"In the ablation, switching off **{worst}** hurts most: recall "
                f"{w['recall']['mean'] * 100:.0f}% and triage accuracy "
                f"{w['triage_accuracy']['mean']:.2f}. Several other single-mechanism deltas sit "
                f"within seed noise at n={n}; [RESULTS.md](RESULTS.md) shows them all.",
            ]
        out += ["", "![Quality vs cost](results/pareto.png)", ""]
    if perf:
        cases = perf["cases"]
        flagged = sum(bool(c["regressed"]) for c in cases)
        correct = sum(bool(c["correct"]) for c in cases)
        rule = sum(c["rule_diagnosis"] == c["expected"] for c in cases)
        held = perf.get("false_alarm_detail") or {}
        false_alarm = bool(held.get("flagged") or held.get("server_signals"))
        out += [
            f"**Performance A/B, {cases[0]['defect']}–{cases[-1]['defect']} against a clean build "
            f"({perf['iterations']} iterations each, same host):** {flagged}/{len(cases)} defects "
            f"flagged beyond the measured noise band, {correct}/{len(cases)} bottleneck classes "
            f"correct (rule-based check: {rule}/{len(cases)}), and "
            f"{_n(int(false_alarm), 'false alarm')} on 1 held-out clean-vs-clean repeat. Agent cost "
            "for "
            f"the whole benchmark: {_k(perf['agent_tokens'])} tokens.",
            "",
        ]
    if func and "memory" in func:
        m = func["memory"]
        r1, r2, r3 = m["run1_cold"], m["run2_with_lessons"], m["run3_incremental"]
        d2 = 1 - r2["tokens_total"] / r1["tokens_total"]
        d3 = 1 - r3["cost_usd_list_equivalent"] / r1["cost_usd_list_equivalent"]
        same = "the same" if r3["recall"] == r1["recall"] else "a different"
        out += [
            f"**Memory (same store, seed 0):** with {m['lessons_after_run1']} lessons from run 1, "
            f"run 2 needed {_n(r2['escalations'], 'escalation')} instead of {r1['escalations']} and "
            f"{d2:.0%} fewer tokens. Run 3, with diff-aware incremental reuse, cost "
            f"**{d3:.0%} less** than run 1 ({_k(r3['tokens_total'])} tokens vs "
            f"{_k(r1['tokens_total'])}) at {same} recall.",
            "",
        ]
    if func and "injection" in func:
        inj = func["injection"]
        adv = [c for c in inj["cases"] if c["label"] == "injection"]
        ben = [c for c in inj["cases"] if c["label"] != "injection"]
        pd = inj["poisoned_doc"]
        out += [
            "**Guardrails:** the poisoned requirements doc was "
            f"{'quarantined' if pd['quarantined'] else 'NOT quarantined'} at ingestion and "
            f"{'never' if not pd['ever_retrieved'] else 'was'} retrieved into a prompt; the "
            f"adversarial set scored {sum(c['quarantined'] for c in adv)}/{len(adv)} detected and "
            f"{sum(c['quarantined'] for c in ben)}/{len(ben)} benign texts flagged. That set was "
            "written by the project author, so it is not an independent benchmark.",
            "",
        ]
    out.append(
        "Full tables, per-category recall, the ablation and the perf confusion data: "
        "[RESULTS.md](RESULTS.md), generated by `agentqa eval` from `results/*.json`."
    )
    return "\n".join(out)


def readme_results_from_files(func_path: Path | None, perf_path: Path | None) -> str:
    func = json.loads(func_path.read_text()) if func_path else None
    perf = json.loads(perf_path.read_text()) if perf_path else None
    return readme_results(func, perf)


def update_readme(func_path: Path | None, perf_path: Path | None, readme: Path = README) -> Path:
    text = readme.read_text(encoding="utf-8")
    start, stop = text.index(BEGIN) + len(BEGIN), text.index(END)
    body = readme_results_from_files(func_path, perf_path)
    readme.write_text(text[:start] + "\n" + body + "\n" + text[stop:], encoding="utf-8")
    return readme
