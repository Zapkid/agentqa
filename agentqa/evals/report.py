"""RESULTS.md and charts, generated only from results/*.json (never hand-edited)."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

from agentqa.config import REPO_ROOT

RESULTS = REPO_ROOT / "results"
SURFACE, TEXT, MUTED = "#fcfcfb", "#0b0b0b", "#52514e"
BLUE, ORANGE, AQUA = "#2a78d6", "#eb6834", "#1baf7a"


def _m(agg: dict[str, Any], key: str, fmt: str = "{:.2f}", pct: bool = False) -> str:
    v = agg.get(key)
    if not isinstance(v, dict):
        return "n/a"
    scale = 100 if pct else 1
    mean, lo, hi = v["mean"] * scale, v["min"] * scale, v["max"] * scale
    if lo == hi:
        return fmt.format(mean)
    return f"{fmt.format(mean)} ({fmt.format(lo)}–{fmt.format(hi)})"


def pareto_chart(strategies: dict[str, Any], out: Path) -> Path:
    fig, ax = plt.subplots(figsize=(7.5, 4.6), facecolor=SURFACE)
    ax.set_facecolor(SURFACE)
    pts = []
    for name, data in strategies.items():
        a = data["aggregate"]
        x, y = a["cost_usd_list_equivalent"]["mean"], a["recall"]["mean"] * 100
        pts.append((x, y, name))
    frontier: list[tuple[float, float, str]] = []
    for x, y, n in sorted(pts):
        if not frontier or y > frontier[-1][1]:
            frontier.append((x, y, n))
    for x, y, n in pts:
        main = n in ("S0", "S1", "S2", "S3")
        color = ORANGE if n == "S3" else (BLUE if main else MUTED)
        ax.scatter(
            [x], [y], s=70 if main else 30, color=color, zorder=3, edgecolor=SURFACE, linewidth=1.5
        )
        if main or y < frontier[-1][1] - 5:
            ax.annotate(
                n,
                (x, y),
                textcoords="offset points",
                xytext=(6, 4),
                fontsize=8,
                color=TEXT if main else MUTED,
            )
    ax.plot(
        [p[0] for p in frontier],
        [p[1] for p in frontier],
        color=MUTED,
        linestyle="--",
        linewidth=1,
        zorder=2,
        label="Pareto frontier",
    )
    ax.set(
        xlabel="list-equivalent cost per run (USD, simulated pricing)",
        ylabel="bug recall (%)",
        title="Quality vs cost by strategy (S3 = smart dispatcher; grey = S3 ablations)",
    )
    ax.title.set_color(TEXT)
    ax.grid(alpha=0.25, color=MUTED, linewidth=0.6)
    ax.tick_params(colors=MUTED, labelsize=8)
    ax.spines[["top", "right"]].set_visible(False)
    ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(out, dpi=120)
    plt.close(fig)
    return out


def render_results(
    func_path: Path | None, perf_path: Path | None, out: Path = REPO_ROOT / "RESULTS.md"
) -> Path:
    lines = [
        "# Results",
        "",
        "Generated by `agentqa eval` from the JSON files in `results/`; do not edit by hand.",
        "",
    ]
    if func_path:
        data = json.loads(func_path.read_text())
        sim = "simulated" in json.dumps(data.get("profiles", ["simulated"]))
        lines += [
            f"Functional results: `{func_path.name}` (commit `{data['commit']}`, {data['generated_at']}).",
            "",
        ]
        if sim:
            lines += [
                "> **SIMULATED MODELS.** These numbers come from the deterministic simulated models",
                "> (ADR 0003). They measure the pipeline's mechanics: whether Tier 0, the cascade, the",
                "> guards and the triage work as designed, and what each cost mechanism saves. They are",
                "> **not** a measurement of any real LLM. Real-model tables come from `make eval-live`.",
                "",
            ]
        if "matrix" in data:
            lines += [
                "## Profile matrix (strategy S3, mean with min–max over seeds)",
                "",
                "| profile | n | recall | precision | triage acc. | hallucination | validity | cost/run (list $) | cost per bug | p95 LLM latency (s) |",
                "|---|---|---|---|---|---|---|---|---|---|",
            ]
            for prof, d in data["matrix"].items():
                a = d["aggregate"]
                lines.append(
                    f"| {prof} | {a['n']} | {_m(a, 'recall', '{:.0f}%', True)} | {_m(a, 'precision')} | "
                    f"{_m(a, 'triage_accuracy')} | {_m(a, 'hallucination_rate', '{:.0f}%', True)} | "
                    f"{_m(a, 'test_validity_rate', '{:.0f}%', True)} | {_m(a, 'cost_usd_list_equivalent', '{:.3f}')} | "
                    f"{_m(a, 'cost_per_bug_list_equivalent', '{:.4f}')} | {_m(a, 'llm_latency_p95_s', '{:.3f}')} |"
                )
            lines.append("")
        if "strategies" in data:
            st = data["strategies"]
            lines += [
                "## Strategy comparison and ablation (cold cache, fresh store per run)",
                "",
                "| strategy | n | recall | precision | triage acc. | halluc. | tokens | list $ | $ per bug | escalation rate | uncovered | FP on clean |",
                "|---|---|---|---|---|---|---|---|---|---|---|---|",
            ]
            for name, d in st.items():
                a = d["aggregate"]
                lines.append(
                    f"| {name} | {a['n']} | {_m(a, 'recall', '{:.0f}%', True)} | {_m(a, 'precision')} | "
                    f"{_m(a, 'triage_accuracy')} | {_m(a, 'hallucination_rate', '{:.0f}%', True)} | "
                    f"{_m(a, 'tokens_total', '{:.0f}')} | {_m(a, 'cost_usd_list_equivalent', '{:.3f}')} | "
                    f"{_m(a, 'cost_per_bug_list_equivalent', '{:.4f}')} | {_m(a, 'escalation_rate', '{:.2f}')} | "
                    f"{_m(a, 'uncovered', '{:.1f}')} | {_m(a, 'false_positive_findings_on_clean', '{:.1f}')} |"
                )
            if "S0" in st and "S3" in st:
                s0, s3 = st["S0"]["aggregate"], st["S3"]["aggregate"]
                d_recall = (s3["recall"]["mean"] - s0["recall"]["mean"]) * 100
                ratio = s3["cost_usd_list_equivalent"]["mean"] / max(
                    1e-9, s0["cost_usd_list_equivalent"]["mean"]
                )
                ok_q, ok_c = d_recall >= -5, ratio <= 0.5
                lines += [
                    "",
                    "**Hypothesis check** (targets, not claims): S3 within 5 points of S0 recall "
                    f"→ measured {d_recall:+.1f} points ({'met' if ok_q else 'missed'}); S3 at most half of S0's "
                    f"list-equivalent cost → measured {ratio:.0%} of S0 ({'met' if ok_c else 'missed'}).",
                ]
                lines += [
                    "",
                    "Savings attributed to each mechanism (S3 with that mechanism off, relative to S3):",
                    "",
                    "| mechanism off | Δ tokens | Δ list $ | Δ recall (points) |",
                    "|---|---|---|---|",
                ]
                for name, d in st.items():
                    if not name.startswith("S3-no-"):
                        continue
                    a = d["aggregate"]
                    dt = a["tokens_total"]["mean"] - s3["tokens_total"]["mean"]
                    dc = (
                        a["cost_usd_list_equivalent"]["mean"]
                        - s3["cost_usd_list_equivalent"]["mean"]
                    )
                    dr = (a["recall"]["mean"] - s3["recall"]["mean"]) * 100
                    lines.append(f"| {name[6:]} | {dt:+.0f} | {dc:+.4f} | {dr:+.1f} |")
                chart = pareto_chart(st, RESULTS / "pareto.png")
                lines += ["", f"![Quality vs cost]({chart.relative_to(REPO_ROOT)})", ""]
            lines += [
                "Per-category recall (mean over seeds):",
                "",
                "| strategy | "
                + " | ".join(sorted(next(iter(st.values()))["aggregate"]["recall_by_category"]))
                + " |",
                "|---|" + "---|" * len(next(iter(st.values()))["aggregate"]["recall_by_category"]),
            ]
            for name, d in st.items():
                rc = d["aggregate"]["recall_by_category"]
                lines.append(f"| {name} | " + " | ".join(f"{rc[k]:.2f}" for k in sorted(rc)) + " |")
            lines.append("")
        if "memory" in data:
            m = data["memory"]
            lines += [
                "## Memory and incremental runs (same store, seed 0)",
                "",
                f"Lessons stored after run 1: {m['lessons_after_run1']}.",
                "",
                "| run | recall | hallucination | tokens | list $ | escalations |",
                "|---|---|---|---|---|---|",
            ]
            for k in ("run1_cold", "run2_with_lessons", "run3_incremental"):
                r = m[k]
                lines.append(
                    f"| {k} | {r['recall']:.0%} | {r['hallucination_rate']:.0%} | {r['tokens_total']} | "
                    f"{r['cost_usd_list_equivalent']:.4f} | {r['escalations']} |"
                )
            lines.append("")
        if "injection" in data:
            inj = data["injection"]
            lines += [
                "## Prompt injection",
                "",
                f"- Poisoned requirements doc quarantined: **{inj['poisoned_doc']['quarantined']}**; ever retrieved into a prompt: **{inj['poisoned_doc']['ever_retrieved']}**",
                f"- Adversarial set detection rate: **{inj['adversarial_detection_rate']:.0%}**; benign false-positive rate: {inj['benign_false_positive_rate']:.0%} "
                f"({inj['decided_by_classifier']} decided by the classifier). Caveat: {inj['caveat']}.",
                "",
            ]
        if "judge_calibration" in data:
            jc = data["judge_calibration"]
            lines += [
                "## Judge calibration",
                "",
                f"Agreement with self-labelled set (within 1 point on accuracy and actionability): "
                f"**{jc['agreement_rate_within_1']:.0%}** of {jc['n']}. {jc['note']}.",
                "",
            ]
    if perf_path:
        p = json.loads(perf_path.read_text())
        lines += [
            f"## Performance A/B benchmark (`{perf_path.name}`, commit `{p['commit']}`)",
            "",
            f"Host: {p['host']}. Iterations per build: {p['iterations']}. Relative numbers only.",
            "",
            f"- Perf-defect recall: **{p['perf_defect_recall']:.0%}**; bottleneck-classification accuracy "
            f"(model): **{p['bottleneck_accuracy']:.0%}**; rule-based diagnosis accuracy: {p['rule_diagnosis_accuracy']:.0%}",
            f"- False-alarm rate on clean-vs-clean repeats: **{p['false_alarm_rate_clean_vs_clean']:.0%}**; "
            f"noise band: p95 ±{p['noise_band']['p95_log_ratio']:.2f} log-ratio, throughput ±{p['noise_band']['rps_log_ratio']:.2f}",
            f"- Agent cost for the whole benchmark: {p['agent_tokens']} tokens (${p['agent_cost_usd_list_equivalent']:.4f} list-equivalent)",
            "",
            "| defect | expected | regressed | diagnosis | rule check | escalation path |",
            "|---|---|---|---|---|---|",
        ]
        for c in p["cases"]:
            lines.append(
                f"| {c['defect']} | {c['expected']} | {c['regressed']} | {c['diagnosis']} | {c['rule_diagnosis']} | {' → '.join(c['triage_path'])} |"
            )
        lines.append("")
        for c in p["cases"]:
            if c.get("chart") and Path(c["chart"]).exists():
                dest = RESULTS / f"perf-{c['defect']}.png"
                dest.write_bytes(Path(c["chart"]).read_bytes())
                lines.append(f"![{c['defect']}]({dest.relative_to(REPO_ROOT)})")
        lines.append("")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out
